/* elfrtgen — embeds the ELF-runtime image into a generated C++ source.
 *
 * Usage: elfrtgen <image.bin> <syms.txt> <out.cpp> <pub-name>...
 *
 * <image.bin> is the flat binary of the linked freestanding runtime
 * (objcopy -O binary of a fully linked small ELF); because the image bytes
 * are copied verbatim into compiler-produced executables, every relicatable
 * reference inside them stays valid. <syms.txt> is `nm` output of the same
 * image ("address type name" lines); only the symbol names given as extra
 * arguments are exported to the generated table. The output declares:
 *   const unsigned char encrt_image[];
 *   unsigned long encrt_image_len;
 *   struct ElfRtSym { const char* name; unsigned long off; } encrt_syms[];
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static unsigned char* image_buf;
static long image_len;

static void* xread(const char* path, long* len) {
    FILE* f = fopen(path, "rb");
    if (!f) { perror(path); exit(1); }
    fseek(f, 0, SEEK_END);
    long n = ftell(f);
    fseek(f, 0, SEEK_SET);
    unsigned char* p = malloc((size_t)n);
    if (!p) { fprintf(stderr, "elfrtgen: out of memory\n"); exit(1); }
    if (n > 0 && fread(p, 1, (size_t)n, f) != (size_t)n) {
        fprintf(stderr, "elfrtgen: short read on %s\n", path);
        exit(1);
    }
    fclose(f);
    *len = n;
    return p;
}

static unsigned long parse_hex16(const char* s) {
    unsigned long v = 0;
    for (int i = 0; i < 16 && s[i]; i++) {
        char c = s[i];
        int d;
        if (c >= '0' && c <= '9') d = c - '0';
        else if (c >= 'a' && c <= 'f') d = c - 'a' + 10;
        else if (c >= 'A' && c <= 'F') d = c - 'A' + 10;
        else return ~0UL;
        v = v * 16UL + (unsigned long)d;
    }
    return v;
}

int main(int argc, char** argv) {
    if (argc < 4) {
        fprintf(stderr, "usage: elfrtgen <image.bin> <syms.txt> <out.cpp> <pub>...\n");
        return 1;
    }
    image_buf = xread(argv[1], &image_len);
    long sym_len;
    unsigned char* sym_buf = xread(argv[2], &sym_len);

    FILE* out = fopen(argv[3], "wb");
    if (!out) { perror(argv[3]); return 1; }

    fprintf(out, "// Generated by tools/elfrtgen.c from the freestanding ELF runtime\n");
    fprintf(out, "// (runtime/elfrt/enc_rt.c). Do not edit by hand.\n");
    fprintf(out, "#include <cstddef>\n\n");
    fprintf(out, "namespace backend {\n\n");
    /* A zero-length image (placeholder builds on hosts without a System V
     * ELF toolchain) must not emit `encrt_image[] = {}` — zero-size arrays
     * are ill-formed, and MinGW gcc rejects them as hard errors. Seal a
     * 0-byte image with one filler byte; the image is unusable for
     * execution anyway because no runtime symbols exist to bind. */
    long emit = image_len > 0 ? image_len : 1;
    fprintf(out, "const unsigned char encrt_image[] = {");
    for (long i = 0; i < emit; i++) {
        if (i) {
            if (i % 16 == 0) fprintf(out, ",\n    ");
            else fprintf(out, ",");
        }
        fprintf(out, "%u", i < image_len ? (unsigned)image_buf[i] : 0u);
    }
    fprintf(out, "};\n");
    fprintf(out, "unsigned long encrt_image_len = %ldUL;\n\n", emit);

    fprintf(out, "struct ElfRtSym { const char* name; unsigned long off; };\n");
    fprintf(out, "const ElfRtSym encrt_syms[] = {\n");
    int count = 0;
    /* split syms buffer into lines */
    char* text = malloc((size_t)sym_len + 1);
    memcpy(text, sym_buf, (size_t)sym_len);
    text[sym_len] = '\0';
    for (char* line = strtok(text, "\n"); line; line = strtok(NULL, "\n")) {
        if (strlen(line) < 20) continue;
        unsigned long addr = parse_hex16(line);
        if (addr == ~0UL) continue;
        const char* type = line + 16;
        if (*type != ' ') continue;
        const char* name = line + 19;           // addr(16) ' ' type(1) ' ' name
        if (*name == '\0') continue;
        for (int a = 4; a < argc; a++) {
            if (strcmp(name, argv[a]) == 0) {
                fprintf(out, "    {\"%s\", %luUL},\n", name, addr);
                count++;
            }
        }
    }
    /* A table with zero matched symbols would be `%s[] = {}` — a zero-size
     * array, ill-formed C++ (MinGW gcc hard-errors on it). Always terminate
     * with a sentinel so the array is never empty; the count below governs
     * how many entries are bound. */
    fprintf(out, "    {NULL, 0UL},\n");
    fprintf(out, "};\n");
    fprintf(out, "unsigned long encrt_syms_count = %dUL;\n\n", count);
    fprintf(out, "}  // namespace backend\n");
    fclose(out);
    return 0;
}
